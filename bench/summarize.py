#!/usr/bin/env python3
"""Turn bench/results/summary.json + labels.csv into RESULTS.md.

Precision per rule = TP / (TP + FP) over the rows that have a label.
Rows left blank or marked UNSURE are reported as "unreviewed" and excluded
from the precision figure, so the number only ever reflects findings a human
actually looked at.
"""

from __future__ import annotations

import csv
import json
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
RES = HERE / "results"


def main() -> None:
    summary = json.loads((RES / "summary.json").read_text())
    labels = list(csv.DictReader((RES / "labels.csv").open()))

    rules = sorted({k.split(":", 1)[1] for r in summary for k in r if k.startswith("rule:")})
    lines = ["# Benchmark results", ""]
    lines.append(
        "Generated by `bench/summarize.py` from `bench/results/summary.json` and `bench/results/labels.csv`. Each labelled row was read in context and judged true or false positive; rows marked *first-pass* were reviewed with assistant help and are being confirmed by the maintainer."
    )
    lines.append("")
    lines.append("## Throughput and findings per repository")
    lines.append("")
    lines.append(
        "| Repository | Files | Seconds | Files/s | Findings | " + " | ".join(rules) + " |"
    )
    lines.append("|---|---:|---:|---:|---:|" + "---:|" * len(rules))
    tot_files = tot_sec = tot_find = 0
    for r in summary:
        if r.get("status") != "ok":
            lines.append(
                f"| {r['repo']} | {r['status']} | | | | " + " | ".join("" for _ in rules) + " |"
            )
            continue
        fps = r["files_scanned"] / r["seconds"] if r["seconds"] else 0
        cells = [str(r.get(f"rule:{k}", 0)) for k in rules]
        lines.append(
            f"| {r['repo']} | {r['files_scanned']} | {r['seconds']} | {fps:.0f} | {r['total']} | "
            + " | ".join(cells)
            + " |"
        )
        tot_files += r["files_scanned"]
        tot_sec += r["seconds"]
        tot_find += r["total"]
    lines.append(
        f"| **Total** | **{tot_files}** | **{tot_sec:.2f}** | **{tot_files / tot_sec if tot_sec else 0:.0f}** | **{tot_find}** | "
        + " | ".join("" for _ in rules)
        + " |"
    )
    lines.append("")

    tp = defaultdict(int)
    fp = defaultdict(int)
    un = defaultdict(int)
    for row in labels:
        lab = (row.get("label") or "").strip().upper()
        if lab == "TP":
            tp[row["rule_id"]] += 1
        elif lab == "FP":
            fp[row["rule_id"]] += 1
        else:
            un[row["rule_id"]] += 1

    lines.append("## Precision per rule (hand-labelled)")
    lines.append("")
    lines.append("| Rule | Reviewed | True positives | False positives | Precision | Unreviewed |")
    lines.append("|---|---:|---:|---:|---:|---:|")
    T = F = U = 0
    for k in rules:
        n = tp[k] + fp[k]
        prec = f"{tp[k] / n:.0%}" if n else "n/a"
        lines.append(f"| {k} | {n} | {tp[k]} | {fp[k]} | {prec} | {un[k]} |")
        T += tp[k]
        F += fp[k]
        U += un[k]
    n = T + F
    lines.append(
        f"| **All** | **{n}** | **{T}** | **{F}** | **{T / n if n else 0:.0%}** | **{U}** |"
    )
    lines.append("")
    lines.append(
        "Precision is computed only over reviewed rows. Recall is not measured here: it would need a ground-truth set of every real issue in each repository, which does not exist."
    )
    (HERE / "RESULTS.md").write_text("\n".join(lines) + "\n")
    print((HERE / "RESULTS.md").read_text())


if __name__ == "__main__":
    main()
